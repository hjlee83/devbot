def test_ambiguous_specification_raises_when_multiple_files_match(tmp_path: Path) -> None:
    directory = tmp_path / "specifications"
    directory.mkdir()
    (directory / "099-sample-a.md").write_text(_MINIMAL_VALID, encoding="utf-8")
    (directory / "099-sample-b.md").write_text(_MINIMAL_VALID, encoding="utf-8")

    try:
        validate_specification_file(tmp_path, 99)
        raise AssertionError("expected AmbiguousSpecificationError")
    except AmbiguousSpecificationError:
        pass


def test_unreadable_specification_raises_load_error(tmp_path: Path) -> None:
    directory = tmp_path / "specifications"
    directory.mkdir()
    # A directory matching the glob pattern is "found" but cannot be read as
    # text - a portable, permission-independent way to trigger an I/O error.
    (directory / "099-broken.md").mkdir()

    try:
        validate_specification_file(tmp_path, 99)
        raise AssertionError("expected SpecificationLoadError")
    except SpecificationLoadError:
        pass


def test_validate_specification_file_end_to_end_passes(tmp_path: Path) -> None:
    directory = tmp_path / "specifications"
    directory.mkdir()
    (directory / "099-sample.md").write_text(_MINIMAL_VALID, encoding="utf-8")

    result = validate_specification_file(tmp_path, 99)

    assert result.passed is True
    assert result.specification_path == directory / "099-sample.md"


