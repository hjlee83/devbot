def _render_canonical_specification(tmp_path: Path) -> str:
    tasks_dir = tmp_path / "tasks"
    tasks_dir.mkdir()
    (tasks_dir / "099-sample.md").write_text(_GENERATOR_CONTRACT, encoding="utf-8")
    client = MagicMock()
    client.list_issues.return_value = [_issue(1, "Task 099: Sample Task Marker Zebra")]
    evidence = gather_task_evidence(client, _repository(), 99, tasks_dir=tasks_dir)
    return render_specification(evidence)


def test_canonical_generator_output_passes(tmp_path: Path) -> None:
    content = _render_canonical_specification(tmp_path)

    result = validate_specification_text(content, task_number=99, specification_path=_SPEC_PATH)

    assert result.passed is True
    assert result.errors == ()
    assert result.warnings == ()


def test_repeated_validation_of_identical_bytes_is_equivalent() -> None:
    first = _validate()
    second = _validate()

    assert first == second


