def test_minimal_valid_skeleton_passes() -> None:
    result = _validate()

    assert result.passed is True
    assert result.errors == ()
    assert result.warnings == ()


def _repository(**overrides: object) -> RepositoryConfig:
    defaults: dict[str, object] = dict(
        owner="someone",
        repo="myrepo",
        enabled=True,
        local_path=Path("/tmp/nonexistent-devbot-repo"),
        default_branch="main",
    )
    defaults.update(overrides)
    return RepositoryConfig(**defaults)  # type: ignore[arg-type]


def _issue(number: int, title: str, body: str = "") -> GitHubIssue:
    return GitHubIssue(
        repository="someone/myrepo",
        number=number,
        title=title,
        body=body,
        state="open",
        labels=(),
        created_at=datetime(2026, 7, 18, tzinfo=UTC),
    )


