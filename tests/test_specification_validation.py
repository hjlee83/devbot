_SPEC_PATH = Path("specifications/099-sample.md")


def _validate(text: str = _MINIMAL_VALID, task_number: int = 99):
    return validate_specification_text(text, task_number=task_number, specification_path=_SPEC_PATH)


def _codes(issues) -> list[str]:
    return [issue.code for issue in issues]


