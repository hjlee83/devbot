def test_invalid_task_number_raises_for_zero_and_negative(tmp_path: Path) -> None:
    for bad_number in (0, -1):
        try:
            validate_specification_file(tmp_path, bad_number)
        except InvalidTaskNumberError:
            continue
        raise AssertionError(f"expected InvalidTaskNumberError for {bad_number}")


