def test_render_json_report_is_valid_and_deterministic() -> None:
    import json

    result = _validate()

    first = render_validation_report(result, output_format="json")
    second = render_validation_report(result, output_format="json")

    assert first == second
    payload = json.loads(first)
    assert payload["task_number"] == 99
    assert payload["passed"] is True
    assert payload["errors"] == []
    assert payload["warnings"] == []


def test_render_json_report_includes_issue_fields() -> None:
    import json

    text = _MINIMAL_VALID.replace(
        "## Background\n\nSample background.\n\n", "## Background\n\n"
    )
    result = _validate(text)

    payload = json.loads(render_validation_report(result, output_format="json"))

    assert payload["passed"] is False
    assert any(issue["code"] == "SPV-005" for issue in payload["errors"])
    for issue in payload["errors"]:
        assert set(issue.keys()) == {"code", "severity", "message", "section", "line"}
